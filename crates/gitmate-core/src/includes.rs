//! Per-profile include files, e.g. `~/.config/gitmate/includes/work.gitconfig`.
//!
//! The files are owned by GitMate and regenerated from `profiles.toml`.
//! Their content is written by `git config --file`, never by hand.

use std::path::Path;

use crate::error::{Error, Result};
use crate::fsutil;
use crate::git::Git;
use crate::paths::AppPaths;
use crate::profile::Profile;
use crate::ssh;

const HEADER: &str = "# Generated by GitMate from profiles.toml. Changes here are overwritten.\n";

/// The `(key, value)` pairs an include file for `profile` must contain.
pub fn expected_entries(profile: &Profile, paths: &AppPaths) -> Result<Vec<(&'static str, String)>> {
    let mut entries = vec![
        ("user.name", profile.name.clone()),
        ("user.email", profile.email.clone()),
    ];
    if let Some(key) = &profile.ssh_key {
        entries.push((
            "core.sshCommand",
            ssh::ssh_command_for_key(&paths.expand_tilde(key))?,
        ));
    }
    Ok(entries)
}

/// Whether the include file exists and holds exactly the expected values.
pub fn is_current(git: &Git, paths: &AppPaths, profile: &Profile) -> Result<bool> {
    let file = paths.include_file(&profile.id);
    if !file.is_file() {
        return Ok(false);
    }
    let expected = expected_entries(profile, paths)?;
    let actual = git.file_list(&file)?;
    let wanted: Vec<(String, String)> = expected
        .into_iter()
        .map(|(k, v)| (k.to_ascii_lowercase(), v))
        .collect();
    Ok(actual == wanted)
}

/// (Re)generate the include file for `profile` atomically.
pub fn write(git: &Git, paths: &AppPaths, profile: &Profile) -> Result<()> {
    let dir = paths.includes_dir();
    fsutil::ensure_private_dir(&paths.config_dir)?;
    fsutil::ensure_private_dir(&dir)?;
    let entries = expected_entries(profile, paths)?;
    fsutil::atomic_replace_with(&paths.include_file(&profile.id), |tmp| {
        std::fs::write(tmp, HEADER).map_err(|e| Error::io("could not write", tmp, e))?;
        for (key, value) in &entries {
            git.file_set_all(tmp, key, std::slice::from_ref(value))?;
        }
        // Git replaces the file via its own lock file; restore 0600.
        restrict(tmp)
    })
}

pub fn remove(paths: &AppPaths, id: &str) -> Result<()> {
    let file = paths.include_file(id);
    match std::fs::remove_file(&file) {
        Ok(()) => Ok(()),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(()),
        Err(e) => Err(Error::io("could not remove", file, e)),
    }
}

#[cfg(unix)]
fn restrict(path: &Path) -> Result<()> {
    use std::os::unix::fs::PermissionsExt;
    std::fs::set_permissions(path, std::fs::Permissions::from_mode(0o600))
        .map_err(|e| Error::io("could not set permissions on", path, e))
}

#[cfg(not(unix))]
fn restrict(_path: &Path) -> Result<()> {
    Ok(())
}
